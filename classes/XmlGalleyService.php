 * @brief Genera y mantiene la galerada XML de una publicación a partir de su
 *  JATS enriquecido, como hacía el plugin en OJS 3.3 y 3.4.
 *
 * La galerada del plugin se reconoce por su archivo: un archivo de galerada
 * (SUBMISSION_FILE_PROOF) cuyo sourceSubmissionFileId apunta a un JATS de
 * publicación (SUBMISSION_FILE_JATS). Así se distingue de las galeradas XML
 * que el equipo sube a mano, que no se tocan.
 */

namespace APP\plugins\generic\XMLMetadataBuilder\classes;

use APP\core\Application;
use APP\facades\Repo;
use APP\publication\Publication;
use PKP\galley\Galley;
use PKP\submissionFile\SubmissionFile;
use Throwable;

class XmlGalleyService extends JatsEnrichmentService
{
    /** Label of the galley, as in OJS 3.4 */
    public const GALLEY_LABEL = 'XML';

    /**
     * Create or update the XML galley of a publication from its JATS.
     *
     * Never throws: a galley error must not break the publication.
     *
     * @return bool Whether the galley file was created or updated
     */
    public function syncXmlGalley(Publication $publication): bool
    {
        try {
            $jatsFile = $this->getPublicationJatsFile($publication);
            if (!$jatsFile) {
                return false;
            }

            // Spaces in xlink:href become %20 so that Lens can match the images
            // (it applies rawurlencode() to the file names). Only in the galley:
            // Texture needs the original names.
            $content = XMLMetadataProcessor::normalizeUrisInXmlString(
                Repo::submissionFile()->getSubmissionFileContent($jatsFile)
            );

            [$galley, $galleyFile] = $this->findPluginGalley($publication);
            $galley ??= $this->createGalley($publication);

            // After a new version, core clones the galley but it keeps pointing
            // to the file of the previous version's galley: do not modify it.
            if ($galleyFile && (int) $galleyFile->getData('assocId') !== $galley->getId()) {
                $galleyFile = null;
            }

            if (!$galleyFile) {
                $galleyFile = $this->createGalleyFile($galley, $jatsFile, $content);
                $this->syncDependentFiles($jatsFile, $galleyFile);
                $this->logEnrichment($jatsFile, 'galley');
                return true;
            }

            $contentChanged = $this->normalize($content) !== $this->normalize(
                Repo::submissionFile()->getSubmissionFileContent($galleyFile)
            );
            if ($contentChanged) {
                $this->replaceFileContent($galleyFile, $content);
            }
            if ((int) $galleyFile->getData('sourceSubmissionFileId') !== $jatsFile->getId()) {
                Repo::submissionFile()->edit($galleyFile, ['sourceSubmissionFileId' => $jatsFile->getId()]);
            }
            $dependentsChanged = $this->syncDependentFiles($jatsFile, Repo::submissionFile()->get($galleyFile->getId()));

            if ($contentChanged || $dependentsChanged) {
                $this->logEnrichment($jatsFile, 'galley');
                return true;
            }
            return false;
        } catch (Throwable $e) {
            error_log(self::LOG . 'No se pudo generar la galerada XML de la publicación ' . $publication->getId() . ': ' . $e->getMessage());
            return false;
        }
    }

    /**
     * The galley generated by the plugin and its file, if the publication has one.
     *
     * @return array{0: ?Galley, 1: ?SubmissionFile}
     */
    protected function findPluginGalley(Publication $publication): array
    {
        $galleys = Repo::galley()
            ->getCollector()
            ->filterByPublicationIds([$publication->getId()])
            ->getMany();

        foreach ($galleys as $galley) {
            $fileId = (int) $galley->getData('submissionFileId');
            $file = $fileId ? Repo::submissionFile()->get($fileId) : null;
            if (!$file || (int) $file->getData('fileStage') !== SubmissionFile::SUBMISSION_FILE_PROOF) {
                continue;
            }

            $sourceId = (int) $file->getData('sourceSubmissionFileId');
            $source = $sourceId ? Repo::submissionFile()->get($sourceId) : null;
            if ($source && (int) $source->getData('fileStage') === SubmissionFile::SUBMISSION_FILE_JATS) {
                return [$galley, $file];
            }
        }

        return [null, null];
    }

    protected function createGalley(Publication $publication): Galley
    {
        $galley = Repo::galley()->newDataObject([
            'publicationId' => $publication->getId(),
            'label' => self::GALLEY_LABEL,
            'locale' => $publication->getData('locale'),
            'isApproved' => true,
        ]);
        $galleyId = Repo::galley()->add($galley);

        return Repo::galley()->get($galleyId);
    }

    /**
     * Create the galley file (SUBMISSION_FILE_PROOF) and attach it to the galley.
     */
    protected function createGalleyFile(Galley $galley, SubmissionFile $jatsFile, string $content): SubmissionFile
    {
        $tempPath = tempnam(sys_get_temp_dir(), 'xmb_');
        try {
            file_put_contents($tempPath, $content);
            $fileId = app()->get('file')->add(
                $tempPath,
                $this->getSubmissionDir($jatsFile) . '/' . uniqid() . '.xml'
            );
        } finally {
            if (is_file($tempPath)) {
                unlink($tempPath);
            }
        }

        $galleyFile = Repo::submissionFile()->newDataObject([
            'fileId' => $fileId,
            'submissionId' => $jatsFile->getData('submissionId'),
            'fileStage' => SubmissionFile::SUBMISSION_FILE_PROOF,
            'assocType' => Application::ASSOC_TYPE_REPRESENTATION,
            'assocId' => $galley->getId(),
            'sourceSubmissionFileId' => $jatsFile->getId(),
            'genreId' => $jatsFile->getData('genreId'),
            'name' => $jatsFile->getData('name'),
            'uploaderUserId' => Application::get()->getRequest()->getUser()?->getId() ?? $jatsFile->getData('uploaderUserId'),
        ]);
        $galleyFileId = Repo::submissionFile()->add($galleyFile);

        // OJS links the file to the galley on add(), but make sure of it
        $galley = Repo::galley()->get($galley->getId());
        if ((int) $galley->getData('submissionFileId') !== $galleyFileId) {
            Repo::galley()->edit($galley, ['submissionFileId' => $galleyFileId]);
        }

        return Repo::submissionFile()->get($galleyFileId);
    }

    /**
     * Make the dependent files (images) of the galley file the same as the
     * ones of the JATS file.
     *
     * @return bool Whether the dependent files were changed
     */
    protected function syncDependentFiles(SubmissionFile $jatsFile, SubmissionFile $galleyFile): bool
    {
        $names = fn ($files) => collect($files)
            ->map(fn (SubmissionFile $file) => $file->getLocalizedData('name'))
            ->sort()
            ->values()
            ->all();

        $jatsDependents = $this->getDependentFiles($jatsFile)->all();
        $galleyDependents = $this->getDependentFiles($galleyFile)->all();

        if ($names($jatsDependents) === $names($galleyDependents)) {
            return false;
        }

        foreach ($galleyDependents as $dependentFile) {
            Repo::submissionFile()->delete($dependentFile);
        }
        foreach ($jatsDependents as $dependentFile) {
            $this->copyDependentFile($dependentFile, $galleyFile);
        }

        return true;
    }
}
